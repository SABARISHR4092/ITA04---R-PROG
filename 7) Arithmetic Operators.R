# 13. Arithmetic Operations on Two Numbers

num1 <- 20
num2 <- 6

cat("Addition (+):", num1 + num2, "\n")
cat("Subtraction (-):", num1 - num2, "\n")
cat("Multiplication (*):", num1 * num2, "\n")
cat("Division (/):", num1 / num2, "\n")
cat("Modulus (%%):", num1 %% num2, "\n")
cat("Integer Division (%/%):", num1 %/% num2, "\n")


# 14. Simple Interest Calculation

principal <- 1000
rate <- 5
time <- 2

simple_interest <- (principal * rate * time) / 100

cat("Simple Interest is:", simple_interest, "\n")